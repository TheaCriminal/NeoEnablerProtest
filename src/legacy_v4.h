enum { V4_ABSENT = 0, V4_PRESENT = 1, V4_UNKNOWN = -1 };

/* V4_PRESENT when the v4 shim and its call are in place, V4_ABSENT when the original bytes are there. */
static int v4_state(pid_t pid, uintptr_t frame) {
    unsigned char code[sizeof(v4_orig_code)], call[5], helper[sizeof(v4_helper)];
    if (kernel_proc_copyout(pid, frame + V4_CODE_OFF, code, sizeof(code)) || kernel_proc_copyout(pid, frame + V4_CALL_OFF, call, 5) ||
        kernel_proc_copyout(pid, frame + V4_HELPER_OFF, helper, sizeof(helper)) || memcmp(helper, v4_helper, sizeof(helper)))
        return V4_UNKNOWN;
    if (!memcmp(code, v4_hook_code, sizeof(code)) && !memcmp(call, v4_hook_call, 5)) return V4_PRESENT;
    if (!memcmp(code, v4_orig_code, sizeof(code)) && !memcmp(call, v4_orig_call, 5)) return V4_ABSENT;
    return V4_UNKNOWN;
}

/* Restores the original call and code with ShellCore stopped (call first, so no launch runs half-written code).
   0 removed or not present, <0 error. */
static int v4_remove(pid_t pid, uintptr_t frame) {
    if (v4_state(pid, frame) != V4_PRESENT) return 0;
    if (kill(pid, SIGSTOP)) return -2;
    usleep(100000);
    unsigned char code[sizeof(v4_orig_code)], call[5];
    int rc = kernel_proc_copyin(pid, v4_orig_call, frame + V4_CALL_OFF, 5) || kernel_proc_copyout(pid, frame + V4_CALL_OFF, call, 5) ||
             memcmp(call, v4_orig_call, 5) ||
             kernel_proc_copyin(pid, v4_orig_code, frame + V4_CODE_OFF, sizeof(code)) ||
             kernel_proc_copyout(pid, frame + V4_CODE_OFF, code, sizeof(code)) || memcmp(code, v4_orig_code, sizeof(code)) ? -3 : 0;
    if (kill(pid, SIGCONT) && !rc) rc = -4;
    return rc;
}
